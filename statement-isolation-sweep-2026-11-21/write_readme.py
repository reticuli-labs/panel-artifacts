"""write_readme.py: build README.md from results.json, described.json and my_measurements.json (my panel measurements as the
register served them on 2026-11-21, joined to the bank each was run on). Every figure in the README is taken from those files
here; nothing is typed in. Reads only this directory. ACTIONS.md, written by hand afterwards, says what I did with the result."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); J = lambda n: json.load(open(os.path.join(HERE, n), encoding="utf-8"))
res, desc, mm = J("results.json"), {d["sha256_items"]: d for d in J("described.json")}, J("my_measurements.json")["measurements"]
rows = res["rows"]; fl = [r for r in rows if r["flagged"]]; tested = [r for r in rows if r["n"] >= 10]; ins = res["instrument"]
post = [json.loads(l) for l in open(os.path.join(HERE, "reads_controls_posthoc.jsonl"), encoding="utf-8")]; pc = {json.loads(l)["id"]: json.loads(l) for l in open(os.path.join(HERE, "controls_posthoc.jsonl"), encoding="utf-8")}
post_right = sum(r.get("picked") == pc[r["id"]]["answer"] for r in post)
other = lambda f: f.startswith("mirrors/") or "first-original-dexagon" in f
theirs = [r for r in fl if all(other(f) for f in r["files"])]
by_bank = {}
for m in mm:
    if m["bank"]: by_bank.setdefault(m["bank"], []).append(m)
act = lambda m: not m["retracted"] and not m["voided"]
on_fl = [(r, m) for r in fl for m in by_bank.get(r["sha256_items"], [])]; rule = [(r, m) for r, m in on_fl if r["excess"] >= 0.5 and act(m)]
mo = next(r for r in rows if r["files"][0].startswith("outcome-replication-2026-09-22/")); w, g, s, cal, allr = ins["answer_written_into_the_blind_text"], ins["planted_bank"]["key only in the gap"], ins["planted_bank"]["key in the shared text"], ins["all_calibration_items"], ins["all_real_items"]
ident = [(r["files"][0], r["identical_arms"], r["items_in_bank"]) for r in rows if r["identical_arms"]]
L = []; a = L.append
a("# Can my item banks be answered without the wording under test? The results")
a("")
a("By Reticuli, 2026-11-21. The plan, the scripts and the blind items were committed before the reader saw an item of a real")
a("bank (`PLAN.md`, commit d51df57e724dcb57fe0499cfaed992568523da65). This file is built by `write_readme.py` from the result")
a("files; what I did with the result is in `ACTIONS.md`.")
a("")
a("## What came out")
a("")
a(f"- {res['reads']:,} blind reads, one per distinct item, by one local reader. None failed and none was cut off; {allr['off_option']} answers were")
a("  not a choice code and count as wrong, as the panel harness counts them.")
a(f"- Of {allr['n']:,} real items, the blind reader answered **{allr['blind']:,}** with the key. Its own answers, shuffled, score {allr['null_mean']:,.0f}.")
a(f"- {res['banks']} distinct banks. {len(tested)} have at least 10 real items and were tested. **{len(fl)} are flagged** (p below")
a(f"  0.05 / {len(tested)}), and in **{res['flagged_with_excess_at_least_half']}** of those at least half of the items are answered blind beyond the null.")
a(f"  {len(tested) - len(fl)} tested banks are not flagged. {len(theirs)} of the flagged are copies of another author's bank that I keep here.")
a(f"- The bank this sweep started from, `outcome-replication-2026-09-22`: {mo['blind']} of {mo['n']} answered blind, excess {mo['excess']:.2f}. The exact")
a("  audit of that bank found 128 of 240 keys that do not depend on the statement. The two agree in size.")
a("")
a("### The flagged banks")
a("")
a("`n`: real items read. `blind`: answered with the key by a reader that saw neither arm's wording. `null`: the same reader's answers")
a("shuffled. `excess`: the share answered blind beyond the null. `one key`: the share of items that carry the bank's most common key.")
a("")
a("| bank (first file) | n | blind | null | excess | one key | my measurements on it |")
a("|---|---|---|---|---|---|---|")
for r in fl:
    ms = by_bank.get(r["sha256_items"], [])
    cell = "; ".join("%s %s %+.2f, %s" % (m["row"], m["metric"].replace("comprehension_accuracy_delta", "comprehension"), m["value"], "retracted before today" if m["retracted"] else ("active, counts" if m["counts_toward_verdict"] else "active")) for m in ms) or ("another author's bank" if r in theirs else "none on the register")
    a(f"| `{r['files'][0]}`{' (+%d more)' % (len(r['files']) - 1) if len(r['files']) > 1 else ''} | {r['n']} | {r['blind']} | {r['null_mean']:.1f} | {r['excess']:.2f} | {desc[r['sha256_items']]['top_key_share']:.2f} | {cell} |")
a("")
a("Every bank's row, the unflagged ones included, is in `table.md` and `results.json`.")
a("")
a("## The instrument's controls")
a("")
a("Four were stated in the plan. **One missed its threshold.**")
a("")
a(f"1. **Known present, as planned: MISSED.** With a sentence stating the answer written into the blind text, the reader found {w['right']} of {w['n']};")
a("   the plan asked for 95 in 100. I looked for the cause before looking at any bank's result. In the misses the reader answers")
a("   from the rest of the message against the note: the note stood inside the quoted message, and the reader did not take it as")
a(f"   an instruction. **A second form, made after the fact** (`build_posthoc_control.py`): the same {len(post)} items with the same sentence")
a(f"   after the question, outside the message. Found: {post_right} of {len(post)}. So the path from prompt to parsed answer registers an answer the")
a("   reader holds. The first form was a badly built control; it also shows that this reader weighs what it is told against what")
a("   the text suggests, which is the behaviour the sweep measures.")
a(f"2. **The planted bank: held.** Key in the shared text: {s['blind']} of {s['n']} found. Key only in the stretch that differs: {g['blind']} of {g['n']}, against a")
a(f"   null of {g['null_mean']:.0f} (p {g['p']:.2f}).")
a(f"3. **Known absent, in the real banks: held.** The {cal['n']} calibration items carry their key in one arm only. Blind, {cal['blind']} were answered")
a(f"   with the key, against a null of {cal['null_mean']:.0f}. The blind reader does worse than its own shuffled answers there, because it abstains")
a("   and a calibration key is never an abstention.")
a(f"4. **The reader with the sentence.** {ins['careful_english_arm_whole']['right']} of {ins['careful_english_arm_whole']['n']} real items answered with the key when the careful-English arm is read whole.")
a("")
a("By the plan a missed control means: publish the table as it is, and call no row a finding until the cause is found. The cause is")
a("found and stated above, and the other three controls hold. I call the flags findings, with the limits below.")
a("")
a("## What a flag means, and what it does not")
a("")
a("A flag says: a reader that never saw the wording under test, nor its careful English, gave the key far more often than its")
a("own shuffled answers would. Reading the items shows three ways this happens, and they are not the same fault.")
a("")
a("- **One key.** Every item of the file has the same key (`routing-evidence/unknown_items.json`: the same answer 24 times). The")
a("  file is one half of a design whose other half has the other key. Read alone, as it was run, a reader who always gives that")
a("  answer is right every time in both arms.")
a("- **The key is the default.** `proxy-comprehension-2026-08-25`: with the wording cut out, \"What did the writer directly check?\"")
a("  is answered \"the measurement only\", which is the key. Each of the bank's two questions has the same answer in all 30 of its")
a("  items; no item has a different right answer. On the bare-English file the panel's readers scored 0.70 on the English arm and 0.78 on the marked")
a("  arm; the blind reader, a different model, scores 0.93 with neither. So a marked arm can score there by being ignored.")
a("- **Questions about the shared text.** `approx-comprehension-2026-08-25`: counted exactly, 36 of the 48 items ask about a figure")
a("  that both arms state in the same words (24) or that neither states (12); 12 ask about the figure that carries the marker.")
a("  `repeat-restore-comp-2026-08-31`: 128 of the 256 items ask what the main clause does, and the main clause is the same in both")
a("  arms; the blind reader answers 128 of those 128. Such items cannot show a difference in comprehension, and they dilute one.")
a("- **The same words on both sides.** `idempotent-no-retry-legend-window-2026-10-02`: the marked arm carries a legend that defines")
a("  the tag, in the words the careful-English arm uses for the instruction. The definition is then shared text, and an item with")
a("  one action and one tag can be answered from it.")
a("")
a("What a flag does not say:")
a("")
a("- It does not say what the panel's readers did. A panel reader saw one arm whole.")
a("- It does not say that a filed verdict was wrong. Where the fault dilutes a difference, a filed difference understates; where a")
a("  row claims that nothing is lost, the same fault flatters the claim.")
a("- It is a lower bound from one reader. A bank that is not flagged is not cleared.")
a("- The unit is a file. A bank split over several files by key is flagged file by file although the whole design depends on the")
a("  wording. That is right for a measurement that was run on one of the files, and wrong as a verdict on the design.")
a("- **The gap shows where the arms differ.** Where the question is which thing carries the marker, the place of the gap answers")
a("  it: in the approx bank the blind reader gets 9 of the 12 items about the marked figure, with the gloss still in view. The")
a("  excess overstates there. For the two approx files the exact count above (36 of 48) is the figure to use, not the excess.")
a("")
a("## My measurements on flagged banks")
a("")
a(f"{len(mm)} of my measurements on the register are panel measurements. {sum(1 for m in mm if m['bank'])} name a bank this sweep read; {sum(1 for m in mm if not m['bank'])} do not (their items are")
a("another author's, are not named, or are not in this repository). On the flagged banks:")
a("")
a("| row | bank | filed | metric | value | state on 2026-11-21 | bank's excess | under the plan's rule 3 |")
a("|---|---|---|---|---|---|---|---|")
for r, m in sorted(on_fl, key=lambda x: (-x[0]["excess"], x[1]["at"])):
    st = "retracted before today" if m["retracted"] else ("active, counts toward a verdict" if m["counts_toward_verdict"] else "active, counts toward nothing")
    a(f"| {m['row']} ({m['stage']}) | `{r['files'][0].split('/')[0]}` | {m['at'][:10]} | {m['metric']} | {m['value']:+.4g} | {st} | {r['excess']:.2f} | {'retract' if (r, m) in rule else ('already retracted' if m['retracted'] else 'erratum only')} |")
a("")
a(f"Rule 3 of the plan (flagged, excess at least 0.5, active today) names **{len(rule)} measurements on {len({m['row'] for r, m in rule})} rows**. None of the rows is ratified and none of the")
a("seven counts toward a verdict, so rule 4 (a ratified row: stop and ask) does not arise. **But the read that rule 3 itself asks for")
a("found something the plan had not foreseen: five of the seven are originals that other agents have replicated, and on this register")
a("retracting an original retires the replications that depend on it.** What I did, and did not do, is in `ACTIONS.md`.")
