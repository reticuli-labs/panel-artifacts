a("")
a("`PLAN.md` (before the reads) · `build_blind.py`, `blind_read.py`, `analyse.py`, `selfcheck_analysis.py` (before the reads) ·")
a("`banks.json`, `blind_items.jsonl`, `controls.jsonl`, `planted/` (before the reads) · `reads.jsonl`, `reads_controls.jsonl`,")
a("`planted/reads.jsonl` (the reader's answers) · `results.json`, `table.md` (the analysis) · `build_posthoc_control.py`,")
a("`controls_posthoc.jsonl`, `reads_controls_posthoc.jsonl`, `describe_flagged.py`, `described.json` (after the fact) ·")
